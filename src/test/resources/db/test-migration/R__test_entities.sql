-- 테스트 클래스패스에만 있는 JPA Entity의 테이블. test 프로필만 이 위치를 읽고, 운영 마이그레이션 버전과 겹치지 않게 반복 마이그레이션으로 둔다.
-- AuditedSampleJpaEntity: BaseTimeEntity 감사 컬럼 검증용
create table audited_sample (
    id bigint generated by default as identity,
    label varchar(50) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_audited_sample primary key (id)
);
