package com.orbit.auth;

/**
 * 계정 폐쇄. 탈퇴를 소유한 모듈이 탈퇴 처리와 같은 트랜잭션에서 호출한다. 닫힌 계정은 외부 식별(카카오·Apple)이 모두 끊겨 같은 외부 계정의 다음 로그인이 새
 * 계정을 만들고, 커밋 뒤에는 그 계정의 refresh token으로 재발급할 수 없으며 그 계정에 발급한 Access Token을 폐기 토큰과 같이 거부한다. 계정 식별자는 다른
 * 모듈의 기록이 계속 참조하므로 남긴다. 제공자 쪽 연결 해제(Apple 토큰 철회·카카오 연결 끊기)에 필요한 값은 해제 대기로 옮겨 두며, 해제가 실패해도 폐쇄는
 * 되돌리지 않는다.
 */
public interface AccountClosure {

    /**
     * 계정을 닫는다. 호출자 트랜잭션에 참여하므로 호출자가 롤백하면 외부 식별·기기 세션·토큰이 그대로 남는다. 이미 닫힌 계정이면 저장된 상태를 바꾸지 않고, 커밋
     * 뒤 토큰 거부만 다시 확정한다.
     *
     * <p>이 호출 전에 호출자가 바꾼 내용이 호출 중에 DB에 반영될 수 있고, 그때의 DB 오류도 이 호출에서 날 수 있다. 호출자가 다루던 객체는 호출 뒤에도 계속
     * 쓸 수 있다.
     *
     * <p>계정 행 잠금은 호출자 트랜잭션이 끝날 때까지 유지된다. 이 메서드가 던진 예외는 호출자 트랜잭션을 롤백 전용으로 만들므로, 잡고 계속 진행해도 커밋할 수
     * 없다.
     *
     * @throws com.orbit.shared.error.BusinessException 계정이 없으면 AUTH-004
     * @throws org.springframework.dao.DataAccessException 호출자나 폐쇄가 바꾼 내용을 DB에 반영하지 못하면
     */
    void close(Long accountId);
}
