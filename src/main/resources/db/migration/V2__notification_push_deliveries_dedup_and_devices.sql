-- notification: 기사 앱 푸시 발신 대기열, 재전송 중복 방지 제약, 참여 요청 결과 알림의 관련 참여 요청, 앱 푸시 기기를 한 번에 더한다.
-- 컬럼 순서는 각 JPA Entity의 필드 순서를 따른다.

-- 기사 앱 푸시 발신 대기열(ADR-004 기사 앱 푸시 발신 대기열). 발신 대기는 알림과 다른 애그리게잇이라 notification_id를 FK 없이 식별자로만 둔다.
create table notification_deliveries (
    id bigint generated by default as identity,
    notification_id bigint not null,
    recipient_account_id bigint not null,
    channel varchar(20) not null,
    status varchar(20) not null,
    attempts integer not null,
    next_attempt_at timestamp(6) with time zone not null,
    last_error varchar(500),
    provider_message_id varchar(255),
    sent_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_notification_deliveries primary key (id),
    constraint uk_notification_deliveries_notification_channel unique (notification_id, channel)
);

create index ix_notification_deliveries_status_next_attempt on notification_deliveries (status, next_attempt_at);

-- 같은 일(받는 계정·종류·작업·알림 시각)의 작업 알림은 한 행만 둔다. 다시 전달된 이벤트가 동시에 처리돼도 하나만 남기는 마지막 방어선이다(ADR-004 소비 측 멱등).
-- 제약을 걸기 전에, 이 제약이 없던 동안 재전송으로 중복 생성된 알림은 가장 먼저 만든 행만 남기고 지운다. 발신 대기열은 위에서 새로 만들어 지울 행이 없다.
-- work_id가 비어 있는 알림은 PostgreSQL이 NULL을 서로 다른 값으로 보므로 이 제약으로 막지 못한다.
delete from notifications
where id in (
    select id from (
        select id, row_number() over (partition by member_id, type, work_id, notified_at order by id) as duplicate_rank
        from notifications
        where work_id is not null
    ) ranked
    where duplicate_rank > 1
);

alter table notifications
    add constraint uk_notifications_member_type_work_notified unique (member_id, type, work_id, notified_at);

-- 참여 요청 결과 알림이 가리키는 참여 요청([알림] 기능명세 §5 관련 참여 요청, 딥링크 대상). organization이 소유한 식별자라 FK 없이 둔다.
-- 같은 참여 요청의 같은 종류 알림은 한 행만 둔다. 작업이 없는 알림이라 위 제약이 막지 못하는 재전송 중복을 막는다.
-- 작업 알림은 participation_request_id가 비어 있어 이 제약에 걸리지 않는다.
alter table notifications add column participation_request_id bigint;

alter table notifications
    add constraint uk_notifications_member_type_participation_request unique (member_id, type, participation_request_id);

-- 앱 푸시 기기(notification 구현 결정 '앱 푸시 기기'). FCM 등록 토큰마다 한 행이고 등록은 토큰 기준 upsert라 토큰에 유일 제약을 둔다.
-- 계정은 auth가 소유한 식별자라 FK 없이 둔다. member_id 인덱스는 계정의 기기 조회(발신)와 탈퇴한 계정의 기기 삭제에 쓴다.
create table push_devices (
    id bigint generated by default as identity,
    member_id bigint not null,
    platform varchar(20) not null,
    token varchar(1024) not null,
    registered_at timestamp(6) with time zone not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_push_devices primary key (id),
    constraint uk_push_devices_token unique (token)
);

create index ix_push_devices_member on push_devices (member_id);
