-- 초기 스키마. 컬럼 순서는 각 JPA Entity의 필드 순서를 따른다.
-- enum 컬럼에는 CHECK 제약을 두지 않는다. 값 검증의 원본은 Domain이며, 값 추가마다 마이그레이션이 필요해지는 것을 피한다.
-- 다른 모듈이 소유한 테이블의 식별자는 FK 없이 둔다(모듈 간 논리 참조). FK는 같은 모듈 안의 부모–자식에만 둔다.

