-- 초기 스키마. 컬럼 순서는 각 JPA Entity의 필드 순서를 따른다.
-- enum 컬럼에는 CHECK 제약을 두지 않는다. 값 검증의 원본은 Domain이며, 값 추가마다 마이그레이션이 필요해지는 것을 피한다.
-- 다른 모듈이 소유한 테이블의 식별자는 FK 없이 둔다(모듈 간 논리 참조). FK는 같은 모듈 안의 부모–자식에만 둔다.

-- user
create table app_user (
    id bigint generated by default as identity,
    display_name varchar(100) not null,
    constraint pk_app_user primary key (id)
);

-- auth
create table accounts (
    id bigint generated by default as identity,
    registered_at timestamp(6) with time zone not null,
    constraint pk_accounts primary key (id)
);

create table oauth_credentials (
    id bigint generated by default as identity,
    account_id bigint not null,
    provider varchar(16) not null,
    oauth_uid varchar(64) not null,
    constraint pk_oauth_credentials primary key (id),
    constraint uk_oauth_credentials_provider_uid unique (provider, oauth_uid),
    constraint fk_oauth_credentials_account foreign key (account_id) references accounts (id)
);

create table apple_refresh_tokens (
    id bigint generated by default as identity,
    account_id bigint not null,
    client_id varchar(255) not null,
    encrypted_token varchar(2048) not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_apple_refresh_tokens primary key (id),
    constraint uk_apple_refresh_tokens_account_client unique (account_id, client_id),
    constraint fk_apple_refresh_tokens_account foreign key (account_id) references accounts (id)
);

-- organization
create table companies (
    id bigint generated by default as identity,
    code varchar(6) not null,
    name varchar(30) not null,
    industry_code varchar(32) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_companies primary key (id),
    constraint uk_companies_code unique (code)
);

create table retired_company_codes (
    id bigint generated by default as identity,
    company_id bigint not null,
    code varchar(6) not null,
    retired_at timestamp(6) with time zone not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_retired_company_codes primary key (id),
    constraint uk_retired_company_codes_code unique (code)
);

create table company_membership_category (
    id bigint generated by default as identity,
    company_id bigint not null,
    name varchar(10) not null,
    color varchar(7) not null,
    is_deleted boolean not null,
    deleted_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_company_membership_category primary key (id)
);

create table company_technician_category (
    id bigint generated by default as identity,
    company_id bigint not null,
    name varchar(10) not null,
    color varchar(7) not null,
    is_deleted boolean not null,
    deleted_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_company_technician_category primary key (id)
);

-- 직원 유형·기사 유형: 같은 발주사에서 삭제되지 않은 유형끼리만 이름이 유일하다([조직·계정] 정책 §7, 소프트 삭제).
-- 인덱스 이름은 MemberCategoryPersistenceAdapter가 중복 이름 판정에 쓴다.
create unique index uk_company_membership_category_undeleted_name
    on company_membership_category (company_id, name) where is_deleted = false;
create unique index uk_company_technician_category_undeleted_name
    on company_technician_category (company_id, name) where is_deleted = false;

create table company_memberships (
    id bigint generated by default as identity,
    company_id bigint not null,
    member_id bigint not null,
    is_owner boolean not null,
    company_membership_category_id bigint,
    status varchar(16) not null,
    joined_at timestamp(6) with time zone not null,
    status_changed_at timestamp(6) with time zone not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_company_memberships primary key (id),
    constraint uk_company_memberships_company_member unique (company_id, member_id)
);

create table technician (
    id bigint generated by default as identity,
    company_id bigint not null,
    member_id bigint not null,
    company_technician_category_id bigint,
    status varchar(16) not null,
    status_changed_at timestamp(6) with time zone not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_technician primary key (id),
    constraint uk_technician_company_member unique (company_id, member_id)
);

create table participation_requests (
    id bigint generated by default as identity,
    company_id bigint not null,
    member_id bigint not null,
    desired_type varchar(16) not null,
    confirmed_type varchar(16),
    status varchar(16) not null,
    reject_reason varchar(255),
    requested_at timestamp(6) with time zone not null,
    decided_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_participation_requests primary key (id)
);

create index idx_participation_requests_member on participation_requests (member_id);
create index idx_participation_requests_company_status on participation_requests (company_id, status);

-- schedule
create table work (
    id bigint generated by default as identity,
    version bigint not null,
    company_id bigint not null,
    created_by bigint not null,
    registered_at timestamp(6) with time zone not null,
    job_type_id bigint,
    name varchar(100) not null,
    status varchar(20) not null,
    technician_id bigint,
    scheduled_start_at timestamp(6) with time zone,
    expected_duration interval second(6),
    customer_name varchar(50),
    customer_phone varchar(20),
    customer_address varchar(200),
    payment_method varchar(20),
    fee bigint,
    started_at timestamp(6) with time zone,
    completed_at timestamp(6) with time zone,
    cancelled_at timestamp(6) with time zone,
    cancelled_by bigint,
    cancel_reason varchar(30),
    cancel_note varchar(255),
    used_parts varchar(255),
    work_note varchar(255),
    actual_fee bigint,
    actual_payment_method varchar(20),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_work primary key (id)
);

create index ix_work_company_technician_status on work (company_id, technician_id, status);
create index ix_work_company_scheduled_start on work (company_id, scheduled_start_at);
create index ix_work_company_registered on work (company_id, registered_at);
create index ix_work_company_updated on work (company_id, updated_at);

create table work_assignments (
    id bigint generated by default as identity,
    work_id bigint not null,
    technician_id bigint not null,
    assigned_by bigint not null,
    scheduled_start_at timestamp(6) with time zone not null,
    expected_duration interval second(6) not null,
    assigned_at timestamp(6) with time zone not null,
    result varchar(20) not null,
    decided_at timestamp(6) with time zone,
    rejection_reason varchar(20),
    rejection_note varchar(255),
    ended_at timestamp(6) with time zone,
    ended_by bigint,
    end_reason varchar(20),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_work_assignments primary key (id),
    constraint fk_work_assignments_work foreign key (work_id) references work (id)
);

create index ix_work_assignments_work on work_assignments (work_id);
create index ix_work_assignments_technician_start on work_assignments (technician_id, scheduled_start_at);

create table work_site_images (
    id bigint generated by default as identity,
    work_id bigint not null,
    image_url varchar(500) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_work_site_images primary key (id),
    constraint fk_work_site_images_work foreign key (work_id) references work (id)
);

create index ix_work_site_images_work on work_site_images (work_id);

create table work_execution_images (
    id bigint generated by default as identity,
    work_id bigint not null,
    image_type varchar(10) not null,
    image_url varchar(500) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_work_execution_images primary key (id),
    constraint fk_work_execution_images_work foreign key (work_id) references work (id)
);

create index ix_work_execution_images_work on work_execution_images (work_id);
